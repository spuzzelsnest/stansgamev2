# Stan's Game - where the sun and the moon stood over Pegasus Bridge and Sainte-Mere-Eglise on 6 June 1944,
# every 10 minutes from 00:00 to 15:00 British Double Summer Time (UTC+2), for SkyEphemeris1944.cs.
# python3 sky_clock_1944.py > ../../Scripts/Environment/SkyEphemeris1944.cs   (needs: pip install ephem)
import ephem, math
SITES = {"Pegasus": (49.2425, -0.2733), "SainteMere": (49.4086, -1.3155)}
def table(lat, lon):
    o = ephem.Observer(); o.lat = str(lat); o.lon = str(lon); o.elevation = 10; o.pressure = 0
    s, m = ephem.Sun(), ephem.Moon(); rows = []
    for k in range(91):
        o.date = ephem.Date('1944/6/5 22:00') + k * 10 * ephem.minute
        s.compute(o); m.compute(o)
        rows += [math.degrees(s.az), math.degrees(s.alt), math.degrees(m.az), math.degrees(m.alt)]
    return rows
print("// Generated by Models/Source~/sky_clock_1944.py (PyEphem) - do not edit by hand.")
print("namespace StansGame\n{\n    /// <summary>Sun and moon over Normandy, 6 June 1944, every 10 minutes from 00:00 to 15:00 BDST:\n    /// sun azimuth, sun altitude, moon azimuth, moon altitude (degrees; azimuth from north towards east).</summary>")
print("    public static class SkyEphemeris1944\n    {\n        public const int StepMinutes = 10, Steps = 91;")
for name, (lat, lon) in SITES.items():
    r = table(lat, lon)
    print(f"        public static readonly float[] {name} = {{")
    for i in range(0, len(r), 8):
        print("            " + ", ".join(f"{v:.2f}f" for v in r[i:i+8]) + ",")
    print("        };")
print("    }\n}")
